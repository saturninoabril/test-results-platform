/**
 * Playwright Custom Reporter for Test Results Platform
 *
 * This reporter integrates with the Test Results Platform API to provide
 * real-time test result reporting with comprehensive metadata storage.
 */

import type {
  FullConfig, FullResult, Reporter, Suite, TestCase, TestResult, TestError
} from '@playwright/test/reporter';
import { readFileSync, statSync } from 'node:fs';
import { basename } from 'node:path';

// CI metadata from environment variables
const ci = (globalThis as any).process.env.CI_PROVIDER || 'ci_local'; // Ex. github_actions, default ci_local if not set
const run_id = (globalThis as any).process.env.CI_RUN_ID || `run_id_local_${new Date().toISOString()}`; // Unique ID for the test run
const job_id = (globalThis as any).process.env.CI_JOB_ID || `job_id_local_${new Date().toISOString()}`; // Unique ID for the job
const full_repo = (globalThis as any).process.env.CI_FULL_REPO || 'full_repo_local'; // Ex. org/repo
const branch = (globalThis as any).process.env.CI_BRANCH || 'branch_local'; // Branch name
const commit_sha = (globalThis as any).process.env.CI_COMMIT_SHA || 'commit_sha_local'; // Commit SHA

// Server metadata (could be set via env vars or config)
const server_metadata = {
  server: (globalThis as any).process.env.SERVER_TYPE || 'server-local', // Ex. enterprise, community, local
  version: (globalThis as any).process.env.SERVER_VERSION || '1.0.0-local', // Server version
  license: (globalThis as any).process.env.SERVER_LICENSE || 'license-local' // License type if applicable
};

interface ApiConfig {
  baseUrl: string;
  timeout: number;
}

interface SuiteData {
  id: string;
  name: string;
  version: string;
  test_count: number;
  status: string;
  start_time: string;
  framework_metadata?: { name: string; version: string; config: any };
  environment_metadata?: { platform: string; arch: string; nodeVersion: string };
  server_metadata?: { server: string; version: string; license: string };
  ci_run_metadata?: {
    ci: string;
    run_id: string;
    job_id: string;
    full_repo: string;
    branch: string;
    commit_sha: string;
  };
  playwright_test_files?: Record<string, Record<string, string>[]>;
}

interface TestResultData {
  id: string;
  suite_id: string;
  external_id: string;
  title: string;
  full_title: string;
  status: string;
  location?: { file: string; line?: number; column?: number };
  project_name?: string;
  timeout?: number;
  tags?: string[];
  duration?: number;
  start_time: string;
  error_message?: string;
  stack_trace?: string;
}

interface EventData {
  suite_id: string;
  test_external_id?: string;
  event_type: string;
  timestamp: string;
  data?: any;
}

interface EventResponse extends EventData {
  id: string;
  request_id?: string;  // Automatically generated by API for request tracing
  user_id?: string;     // Automatically populated from authenticated context (if available)
  created_at: string;
  updated_at: string;
}

class TestResultsPlatformReporter implements Reporter {
  private config: ApiConfig;
  private suiteId: string | null = null;
  private startTime: Date = new Date();
  private testCount: number = 0;
  private testResultIds: Map<string, string> = new Map(); // external_id -> test_result_id

  constructor(options: { baseUrl?: string; timeout?: number } = {}) {
    this.config = {
      baseUrl: options.baseUrl || 'http://localhost:8000',
      timeout: options.timeout || 10000
    };
  }

  async onBegin(config: FullConfig, suite: Suite) {
    console.log(`🚀 Starting Playwright test run with Test Results Platform integration`);
    console.log(`📡 API Base URL: ${this.config.baseUrl}`);

    const safeConfig = safeConfigExtract(config);

    function safeConfigExtract(obj: FullConfig): any {
      return {
        configFile: obj.configFile,
        rootDir: obj.rootDir,
        forbidOnly: obj.forbidOnly,
        fullyParallel: obj.fullyParallel,
        globalSetup: obj.globalSetup,
        globalTeardown: obj.globalTeardown,
        globalTimeout: obj.globalTimeout,
        grep: obj.grep,
        grepInvert: obj.grepInvert,
        maxFailures: obj.maxFailures,
        preserveOutput: obj.preserveOutput,
        reporter: obj.reporter,
        reportSlowTests: obj.reportSlowTests,
        quiet: obj.quiet,
        shard: obj.shard,
        updateSnapshots: obj.updateSnapshots,
        updateSourceMethod: obj.updateSourceMethod,
        version: obj.version,
        workers: obj.workers,
        webServer: obj.webServer,
        projects: obj.projects.map(p => ({
          grep: p.grep,
          grepInvert: p.grepInvert,
          outputDir: p.outputDir,
          repeatEach: p.repeatEach,
          retries: p.retries,
          name: p.name,
          testDir: p.testDir,
          snapshotDir: p.snapshotDir,
          testIgnore: p.testIgnore,
          testMatch: p.testMatch,
          timeout: p.timeout
        })),
      };
    }

    const test_files: Record<string, Record<string, string>[]> = {};
    for (const test of suite.allTests()) {
      const file = test.location.file;
      if (!file) {
        continue;
      }

      if (test_files[file]) {
        test_files[file].push({ [test.id]: test.title });
      } else {
        test_files[file] = [{ [test.id]: test.title }];
      }
    }

    this.testCount = suite.allTests().length;

    try {
      // Create test suite
      const suiteData: Omit<SuiteData, 'id'> = {
        name: `Playwright Test Run - ${this.startTime.toISOString()}`,
        version: safeConfig.version,
        test_count: this.testCount,
        status: 'running',
        start_time: this.startTime.toISOString(),
        framework_metadata: {
          name: 'playwright',
          version: safeConfig.version || 'unknown',
          config: safeConfig,
        },
        environment_metadata: {
          platform: (globalThis as any).process.platform,
          arch: (globalThis as any).process.arch,
          nodeVersion: (globalThis as any).process.version
        },
        ci_run_metadata: {
          ci,
          run_id,
          job_id,
          full_repo,
          branch,
          commit_sha,
        },
        server_metadata,
        playwright_test_files: test_files,
      };

      const suite_response = await this.createSuite(suiteData);
      this.suiteId = suite_response.id;
      console.log(`📝 Test suite created: ${suite_response.name} (${suite_response.id})`);

      // Send suite started event
      await this.createEvent({
        suite_id: this.suiteId,
        event_type: 'suite_started',
        timestamp: this.startTime.toISOString(),
        data: {
          totalTests: test_files.length,
          config: safeConfig,
          test_files,
          totalProjects: config.projects.length,
          ci,
          run_id,
          job_id,
          full_repo,
          branch,
          commit_sha,
        }
      });

    } catch (error) {
      console.error('❌ Failed to initialize test suite:', error);
    }
  }

  async onTestBegin(test: TestCase, result: TestResult) {
    if (!this.suiteId) {
      console.warn('⚠️ Skipping test begin - suite not initialized');
      return;
    }

    const testId = this.generateTestId(test);
    console.log(`🧪 Starting test: ${test.title} (${testId})`);

    try {
      // Create test result entry
      const testResultData: Omit<TestResultData, 'id'> = {
        suite_id: this.suiteId,
        external_id: testId,
        title: test.title,
        full_title: test.titlePath().join(' › '),
        status: 'running',
        location: {
          file: test.location.file,
          line: test.location.line,
          column: test.location.column
        },
        project_name: result.workerIndex !== undefined ? `Worker ${result.workerIndex}` : undefined,
        timeout: test.timeout,
        tags: this.extractTags(test),
        start_time: new Date().toISOString(),
      };

      const testResultResponse = await this.createTestResult(testResultData);

      // Store the test result ID for later artifact upload
      this.testResultIds.set(testId, testResultResponse.id);

      // Send test started event
      await this.createEvent({
        suite_id: this.suiteId,
        test_external_id: testId,
        event_type: 'test_started',
        timestamp: new Date().toISOString(),
        data: {
          testTitle: test.title,
          fullTitle: test.titlePath().join(' › '),
          estimatedDuration: test.timeout,
          retryIndex: result.retry,
          workerIndex: result.workerIndex
        }
      });

    } catch (error) {
      console.error(`❌ Failed to record test start for ${test.title}:`, error);
    }
  }

  async onTestEnd(test: TestCase, result: TestResult) {
    if (!this.suiteId) {
      console.warn('⚠️ Skipping test end - suite not initialized');
      return;
    }

    const testId = this.generateTestId(test);
    const duration = result.duration;
    const status = this.mapTestStatus(result.status);

    console.log(`${this.getStatusEmoji(status)} Finished test: ${test.title} - ${status} (${duration}ms)`);

    try {
      // Update test result
      const updateData: any = {
        status: status,
        duration: duration,
        end_time: new Date().toISOString()
      };

      if (result.error) {
        updateData.error_message = this.extractErrorMessage(result.error);
        updateData.stack_trace = result.error.stack || '';
      }

      await this.updateTestResult(testId, updateData);

      // Send test ended event
      await this.createEvent({
        suite_id: this.suiteId,
        test_external_id: testId,
        event_type: 'test_ended',
        timestamp: new Date().toISOString(),
        data: {
          testTitle: test.title,
          status: status,
          duration: duration,
          retry: result.retry,
          artifactCount: result.attachments?.length || 0,
          error: result.error ? {
            message: this.extractErrorMessage(result.error),
            stack: result.error.stack
          } : undefined
        }
      });

      // Upload artifacts if any
      if (result.attachments && result.attachments.length > 0) {
        console.log(`📎 Uploading ${result.attachments.length} artifacts for ${test.title}`);
        await this.uploadArtifacts(testId, result.attachments);
      }

    } catch (error) {
      console.error(`❌ Failed to record test end for ${test.title}:`, error);
    }
  }

  async onEnd(result: FullResult) {
    if (!this.suiteId) {
      console.warn('⚠️ Skipping suite end - suite not initialized');
      return;
    }

    const endTime = new Date();
    const duration = endTime.getTime() - this.startTime.getTime();
    const status = this.mapSuiteStatus(result.status);

    console.log(`🏁 Test run completed: ${status} - ${duration}ms total`);

    try {
      // Update suite with final results
      await this.updateSuite(this.suiteId, {
        status: status,
        end_time: endTime.toISOString(),
        duration: duration
      });

      // Send suite ended event
      await this.createEvent({
        suite_id: this.suiteId,
        event_type: 'suite_ended',
        timestamp: endTime.toISOString(),
        data: {
          status: status,
          totalTests: this.testCount,
          duration: duration,
          startedAt: this.startTime.toISOString(),
          endedAt: endTime.toISOString()
        }
      });

      console.log(`✨ Test results successfully uploaded to Test Results Platform`);
      console.log(`📊 View results at: ${this.config.baseUrl}/playwright/test-results?suite_id=${this.suiteId}`);

    } catch (error) {
      console.error('❌ Failed to finalize test suite:', error);
    }
  }

  // API Methods
  private async apiRequest(endpoint: string, method: string = 'GET', data?: any): Promise<any> {
    const url = `${this.config.baseUrl}${endpoint}`;
    const options: RequestInit = {
      method,
      headers: {
        'Content-Type': 'application/json',
      }
    };

    if (data) {
      options.body = JSON.stringify(data);
    }

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), this.config.timeout);

    try {
      const response = await fetch(url, { ...options, signal: controller.signal });
      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`API request failed: ${response.status} ${response.statusText} - ${errorText}`);
      }

      return await response.json();
    } catch (error) {
      clearTimeout(timeoutId);
      throw error;
    }
  }

  private async createSuite(data: Omit<SuiteData, 'id'>): Promise<SuiteData> {
    return await this.apiRequest('/playwright/suites', 'POST', data);
  }

  private async updateSuite(suiteId: string, data: any): Promise<SuiteData> {
    return await this.apiRequest(`/playwright/suites/${suiteId}`, 'PUT', data);
  }


  private async createTestResult(data: Omit<TestResultData, 'id'>): Promise<TestResultData> {
    return await this.apiRequest('/playwright/test-results', 'POST', data);
  }

  private async updateTestResult(externalId: string, data: any): Promise<TestResultData> {
    return await this.apiRequest(`/playwright/test-results/${externalId}?suite_id=${this.suiteId}`, 'PUT', data);
  }

  private async createEvent(data: EventData): Promise<EventResponse> {
    return await this.apiRequest('/playwright/events', 'POST', data);
  }

  private async uploadArtifacts(testId: string, attachments: any[]): Promise<void> {
    if (!attachments || attachments.length === 0) return;

    console.log(`📎 Uploading ${attachments.length} artifacts for test ${testId}...`);

    try {
      // Get the test result ID from our in-memory map
      const testResultId = this.testResultIds.get(testId);
      if (!testResultId) {
        console.warn(`⚠️ No test result ID found for ${testId}, skipping artifact upload`);
        return;
      }

      for (const attachment of attachments) {
        try {
          console.log(`🔗 Uploading artifact: ${attachment.path}, (${attachment.contentType})`);
          await this.uploadSingleArtifact(testResultId, attachment);
        } catch (error) {
          console.error(`❌ Failed to upload artifact ${attachment.name}:`, error);
        }
      }

      console.log(`✅ Successfully uploaded ${attachments.length} artifacts for test ${testId}`);
    } catch (error) {
      console.error(`❌ Failed to upload artifacts for test ${testId}:`, error);
    }
  }

  private async uploadSingleArtifact(testResultId: string, attachment: any): Promise<void> {
    try {
      // Read the file to get its size and content

      if (!attachment.path) {
        console.warn(`⚠️ Attachment ${attachment.name} has no path, skipping`);
        return;
      }

      const filePath = attachment.path;
      const fileName = basename(filePath); // Always use the actual filename from path
      const stats = statSync(filePath);
      const fileSize = stats.size;

      // Extract relative path from test-results directory to preserve folder structure
      const relativePath = this.extractTestResultsPath(filePath);

      // Read file content
      const fileBuffer = readFileSync(filePath);

      // Determine content type based on file extension
      const contentType = this.getContentType(fileName);
      const artifactType = this.getArtifactType(fileName);

      // Step 1: Get presigned upload URL
      const presignedRequest = {
        filename: fileName,
        relative_path: relativePath, // Add relative path to preserve folder structure
        content_type: contentType,
        artifact_type: artifactType,
        file_size: fileSize,
        suite_id: this.suiteId,
        test_result_id: testResultId
      };

      const presignedResponse = await this.apiRequest('/playwright/artifacts/presigned-upload', 'POST', presignedRequest);

      console.log(`📤 Uploading artifact: ${fileName} (${fileSize} bytes)`);

      // Step 2: Upload file to S3 using presigned URL
      await this.uploadFileToPresignedUrl(presignedResponse, fileBuffer);

      // Step 3: Register artifact with the API
      const artifactRequest = {
        type: artifactType,
        filename: fileName,
        storage_path: presignedResponse.storage_path,
        file_size: fileSize,
        content_type: contentType,
        capture_time: new Date().toISOString(),
      };

      // Use the UUID test result ID, not external ID
      await this.apiRequest(`/playwright/test-results/${testResultId}/artifacts`, 'POST', artifactRequest);

      console.log(`✅ Artifact registered: ${fileName}`);

    } catch (error) {
      console.error(`❌ Failed to upload single artifact:`, error);
      throw error;
    }
  }

  private async uploadFileToPresignedUrl(presignedResponse: any, fileBuffer: any): Promise<void> {
    try {
      const formData = new FormData();

      // Add all the fields from the presigned response in the correct order
      if (presignedResponse.fields) {
        for (const [key, value] of Object.entries(presignedResponse.fields)) {
          formData.append(key, value as string);
        }
      }

      // Add the file data last (required for S3 presigned POST)
      const blob = new Blob([fileBuffer]);
      formData.append('file', blob);

      console.log(`🔗 Uploading to: ${presignedResponse.upload_url}`);

      // Upload to the presigned URL
      const uploadResponse = await fetch(presignedResponse.upload_url, {
        method: 'POST',
        body: formData
      });

      if (!uploadResponse.ok) {
        const responseText = await uploadResponse.text();
        console.error(`Upload error response: ${responseText}`);
        throw new Error(`Upload failed: ${uploadResponse.status} ${uploadResponse.statusText}`);
      }

      console.log(`✅ File uploaded to storage successfully`);
    } catch (error) {
      console.error('❌ Failed to upload file to presigned URL:', error);
      throw error;
    }
  }

  private getContentType(fileName: string): string {
    const ext = fileName.toLowerCase().split('.').pop();
    const contentTypes: { [key: string]: string } = {
      'png': 'image/png',
      'jpg': 'image/jpeg',
      'jpeg': 'image/jpeg',
      'gif': 'image/gif',
      'webm': 'video/webm',
      'mp4': 'video/mp4',
      'html': 'text/html',
      'json': 'application/json',
      'txt': 'text/plain',
      'log': 'text/plain',
      'trace': 'application/octet-stream'
    };
    return contentTypes[ext || ''] || 'application/octet-stream';
  }

  private getArtifactType(fileName: string): string {
    const name = fileName.toLowerCase();
    if (name.includes('screenshot') || name.endsWith('.png') || name.endsWith('.jpg') || name.endsWith('.jpeg')) {
      return 'screenshot';
    }
    if (name.includes('video') || name.endsWith('.webm') || name.endsWith('.mp4')) {
      return 'video';
    }
    if (name.includes('trace') || name.endsWith('.trace')) {
      return 'trace';
    }
    if (name.endsWith('.html')) {
      return 'html_report';
    }
    if (name.includes('error') || name.includes('context')) {
      return 'trace';  // Treat error context as trace artifacts
    }
    return 'trace';  // Default to trace instead of other
  }

  // Helper Methods
  private generateTestId(test: TestCase): string {
    // Create a unique ID based on test file, title, and project name to avoid conflicts across browsers
    const file = test.location.file.split('/').pop() || 'unknown';
    const title = test.title.replace(/[^a-zA-Z0-9]/g, '-').toLowerCase();
    const projectName = test.titlePath()[1] || 'unknown-project'; // Second element is usually the project/browser name
    return `${projectName}-${file}-${title}-${test.location.line}`;
  }


  private extractTags(test: TestCase): string[] | undefined {
    // Extract tags from test annotations or title
    const tags: string[] = [];

    // Check for @tags in title
    const tagMatches = test.title.match(/@(\w+)/g);
    if (tagMatches) {
      tags.push(...tagMatches.map(tag => tag.substring(1)));
    }

    return tags.length > 0 ? tags : undefined;
  }

  private mapTestStatus(status: string): string {
    const statusMap: { [key: string]: string } = {
      'passed': 'passed',
      'failed': 'failed',
      'timedOut': 'failed',
      'skipped': 'skipped',
      'interrupted': 'failed'
    };
    return statusMap[status] || 'failed';
  }

  private mapSuiteStatus(status: string): string {
    const statusMap: { [key: string]: string } = {
      'passed': 'passed',
      'failed': 'failed',
      'timedout': 'failed',
      'interrupted': 'cancelled'
    };
    return statusMap[status] || 'failed';
  }

  private extractErrorMessage(error: TestError): string {
    return error.message || error.toString();
  }

  private getStatusEmoji(status: string): string {
    const emojiMap: { [key: string]: string } = {
      'passed': '✅',
      'failed': '❌',
      'skipped': '⏭️',
      'running': '🔄'
    };
    return emojiMap[status] || '❓';
  }

  private extractTestResultsPath(filePath: string): string {
    // Extract path relative to test-results directory to preserve folder structure
    // Example: "/path/to/test-results/example-failing-test-for-artifact-upload-demo-chromium/test-failed-1.png"
    // Should return: "test-results/example-failing-test-for-artifact-upload-demo-chromium/test-failed-1.png"

    const testResultsIndex = filePath.indexOf('test-results');
    if (testResultsIndex !== -1) {
      return filePath.substring(testResultsIndex);
    }

    // Fallback: use just the filename if test-results not found in path
    return basename(filePath);
  }
}

export default TestResultsPlatformReporter;